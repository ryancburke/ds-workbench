"""
Starter Notebook Generator skill.

Takes a workbench session (the runs-store dict) and packages it into a
launchable Databricks-compatible .ipynb notebook that a DS can open,
run cell by cell, and build from.

Entry point:
    from skills.notebook_generator import generate

    result = generate(session_store, filename="my_analysis.ipynb")
    # result["notebook_json"] — write this to disk or return for download
    # result["cells_generated"]
    # result["summary"]
"""

from __future__ import annotations

import json
import textwrap


# ── Notebook format helpers ────────────────────────────────────────────────────

def _nb_cell(cell_type: str, source: str | list[str], **meta) -> dict:
    src = source if isinstance(source, list) else source.splitlines(keepends=True)
    base = {
        "cell_type": cell_type,
        "metadata":  meta.get("metadata", {}),
        "source":    src,
    }
    if cell_type == "code":
        base["execution_count"] = None
        base["outputs"] = []
    return base


def _md(text: str) -> dict:
    return _nb_cell("markdown", textwrap.dedent(text).strip())


def _code(text: str) -> dict:
    return _nb_cell("code", textwrap.dedent(text).strip())


# ── Section builders ───────────────────────────────────────────────────────────

def _header_cells(problem: str, datasets: list[str]) -> list[dict]:
    ds_list = ", ".join(f"`{d}`" for d in datasets) if datasets else "*(none specified)*"
    return [
        _md(f"""\
            # DS Workbench Session Notebook

            **Investigation:** {problem or '*(no problem statement)*'}

            **Datasets:** {ds_list}

            ---
            *Generated by DS Workbench. Run cells top-to-bottom. Each section corresponds to a skill run from your session.*
        """),
        _code("""\
            # Setup
            from pyspark.sql import SparkSession
            import pandas as pd
            import warnings
            warnings.filterwarnings("ignore")

            spark = SparkSession.builder.getOrCreate()
            print("SparkSession ready")
        """),
    ]


def _dataset_cells(datasets: list[str]) -> list[dict]:
    if not datasets:
        return []
    cells: list[dict] = [_md("## Data Loading")]
    load_lines = []
    for ds in datasets:
        var = ds.replace("-", "_")
        load_lines.append(f"# {ds}")
        load_lines.append(f"# df_{var} = spark.read.table('your_catalog.your_schema.{ds}')")
        load_lines.append(f"# df_{var}.display()")
        load_lines.append("")
    cells.append(_code(
        "# Replace table paths with your actual Databricks catalog/schema paths.\n" +
        "\n".join(load_lines)
    ))
    return cells


def _dq_cells(dq_runs: list[dict]) -> list[dict]:
    if not dq_runs:
        return []
    cells: list[dict] = [_md("## Data Quality Assessment")]
    for run in dq_runs:
        if run.get("status") != "complete":
            continue
        label   = run.get("label", "dataset")
        result  = run.get("result", {})
        score   = result.get("overall_score", "?")
        summary = result.get("summary", "")
        findings = result.get("findings", [])
        criticals = [f for f in findings if f.get("severity") == "critical"]
        warnings_ = [f for f in findings if f.get("severity") == "warning"]

        md_lines = [f"### DQ: `{label}`  (score {score}/100)", "", summary, ""]
        if criticals:
            md_lines.append("**Critical issues to fix before modeling:**")
            for f in criticals:
                md_lines.append(f"- `{f.get('column','?')}`: {f.get('description','')}")
            md_lines.append("")
        if warnings_:
            md_lines.append("**Warnings (review before training):**")
            for f in warnings_:
                md_lines.append(f"- `{f.get('column','?')}`: {f.get('description','')}")
        cells.append(_md("\n".join(md_lines)))

        # Suggest remediation code only if there are critical issues
        if criticals:
            fix_lines = [f"# Remediation stubs for {label}"]
            for f in criticals:
                col  = f.get("column", "col")
                kind = f.get("issue_type", "")
                if "null" in kind:
                    fix_lines.append(f"df = df.na.drop(subset=['{col}'])  # or .fillna({{'{col}': ...}})")
                elif "duplicate" in kind:
                    fix_lines.append(f"df = df.dropDuplicates(['{col}'])")
                elif "format" in kind or "type" in kind:
                    fix_lines.append(f"# TODO: cast or clean df['{col}']")
            cells.append(_code("\n".join(fix_lines)))

    return cells


def _leakage_cells(ld_runs: list[dict]) -> list[dict]:
    if not ld_runs:
        return []
    cells: list[dict] = [_md("## Leakage Check")]
    for run in ld_runs:
        if run.get("status") != "complete":
            continue
        label    = run.get("label", "dataset → target")
        result   = run.get("result", {})
        verdict  = result.get("verdict", "clean")
        risk     = result.get("risk_level", "none")
        findings = result.get("findings", [])
        summary  = result.get("summary", "")

        status_icon = {"leakage_detected": "🔴", "suspicious": "🟡", "clean": "🟢"}.get(verdict, "⚪")
        md_lines = [
            f"### Leakage: `{label}`  {status_icon} {verdict.replace('_', ' ').title()} (risk: {risk})",
            "", summary, "",
        ]
        if findings:
            md_lines.append("**Findings:**")
            for f in findings:
                sev = f.get("severity", "info")
                col = f.get("column", "?")
                ft  = f.get("finding_type", "?").replace("_", " ")
                md_lines.append(f"- `{col}` ({sev}): {ft} — {f.get('description','')}")
        cells.append(_md("\n".join(md_lines)))

        if verdict == "leakage_detected":
            leaky_cols = [f.get("column") for f in findings if f.get("severity") == "critical"]
            if leaky_cols:
                cols_str = ", ".join(f"'{c}'" for c in leaky_cols)
                cells.append(_code(
                    f"# Drop leaky columns before training\n"
                    f"leaky_cols = [{cols_str}]\n"
                    f"df_clean = df.drop(*leaky_cols)\n"
                    f"print(f'Dropped {{len(leaky_cols)}} leaky column(s): {{leaky_cols}}')"
                ))
    return cells


def _fe_cells(fe_runs: list[dict]) -> list[dict]:
    if not fe_runs:
        return []
    cells: list[dict] = [_md("## Feature Engineering Pipeline")]
    for run in fe_runs:
        if run.get("status") != "complete":
            continue
        label    = run.get("label", "dataset → target")
        result   = run.get("result", {})
        features = result.get("features", [])
        dropped  = result.get("dropped_cols", [])
        code     = result.get("pyspark_code", "")
        warnings = result.get("warnings", [])

        md_lines = [f"### Feature Engineering: `{label}`"]
        if dropped:
            md_lines.append(f"\n**Columns dropped (identifiers/leaky):** {', '.join(f'`{c}`' for c in dropped)}")
        if warnings:
            md_lines.append("\n**Warnings:**")
            for w in warnings:
                md_lines.append(f"- {w}")
        if features:
            md_lines.append(f"\n**{len(features)} features planned:**")
            for f in features:
                action = f.get("action", "").replace("_", " ")
                impute = f.get("imputation", "none")
                note   = f" + impute ({impute})" if impute not in ("none", None) else ""
                md_lines.append(f"- `{f.get('column')}` → {action}{note} → `{f.get('output_col', '')}`")
        cells.append(_md("\n".join(md_lines)))

        if code:
            cells.append(_code(code))
    return cells


def _model_cells(ms_runs: list[dict]) -> list[dict]:
    if not ms_runs:
        return []
    cells: list[dict] = [_md("## Model Training")]
    for run in ms_runs:
        if run.get("status") != "complete":
            continue
        result = run.get("result", {})
        label  = run.get("label", "dataset → target")
        task   = result.get("task_type", "?").replace("_", " ")
        recs   = result.get("recommendations", [])
        notes  = result.get("readiness_notes", [])

        md_lines = [f"### Model Selection: `{label}`  (task: {task})"]
        if notes:
            md_lines.append("\n**Before training:**")
            for n in notes:
                md_lines.append(f"- {n}")
        if recs:
            md_lines.append("\n**Recommended models (ranked):**")
            for r in recs:
                suit = r.get("suitability", "moderate")
                md_lines.append(f"- **#{r.get('rank', '?')} {r.get('display_name', '')}** ({suit}): {r.get('rationale', '')}")
        cells.append(_md("\n".join(md_lines)))

        # Emit starter code for the top recommendation
        top_code = next((r.get("starter_code", "") for r in recs if r.get("starter_code")), "")
        if top_code:
            cells.append(_md(f"**Starter code — top recommendation:**"))
            cells.append(_code(top_code))

    return cells


def _next_steps_cell(session: dict, store: dict) -> list[dict]:
    has_fe = bool(store.get("feature_engineering", []))
    has_ms = bool(store.get("model_selector", []))
    has_ld = bool(store.get("leakage_detector", []))

    steps = ["## Next Steps", ""]
    steps.append("Based on your session findings, suggested next steps:")
    if has_ld:
        steps.append("- [ ] Confirm leakage check passed (or drop flagged columns)")
    if has_fe:
        steps.append("- [ ] Fit the feature pipeline on **train split only** (avoid data leakage)")
        steps.append("- [ ] Transform both train and test with the fitted pipeline")
    if has_ms:
        steps.append("- [ ] Train the top recommended model on the processed features")
        steps.append("- [ ] Evaluate on the held-out test set")
    steps.append("- [ ] Log experiment metrics to MLflow")
    steps.append("- [ ] Review MLOps checklist before promoting to staging")
    return [_md("\n".join(steps))]


# ── Main entry point ───────────────────────────────────────────────────────────

def generate(session_store: dict, filename: str = "workbench_session.ipynb") -> dict:
    """
    Package a workbench session into a launchable Databricks notebook.

    Args:
        session_store: The runs-store dict from the Dash app (or equivalent
                       dict with keys: session, data_quality, leakage_detector,
                       feature_engineering, model_selector, eda, etc.)
        filename:      Suggested filename for the notebook.

    Returns:
        {
            "notebook_json":    str  — raw .ipynb JSON, ready to write to disk
            "filename":         str  — suggested filename
            "cells_generated":  int  — total cell count
            "skills_included":  list — which skills contributed cells
            "summary":          str  — one-line description
        }
    """
    session  = session_store.get("session") or {}
    problem  = session.get("problem_statement", "")
    datasets = session.get("datasets", [])

    all_cells: list[dict] = []
    skills_included: list[str] = []

    all_cells.extend(_header_cells(problem, datasets))
    all_cells.extend(_dataset_cells(datasets))

    dq_runs = [r for r in session_store.get("data_quality", []) if r.get("status") == "complete"]
    if dq_runs:
        all_cells.extend(_dq_cells(dq_runs))
        skills_included.append("data_quality")

    ld_runs = [r for r in session_store.get("leakage_detector", []) if r.get("status") == "complete"]
    if ld_runs:
        all_cells.extend(_leakage_cells(ld_runs))
        skills_included.append("leakage_detector")

    fe_runs = [r for r in session_store.get("feature_engineering", []) if r.get("status") == "complete"]
    if fe_runs:
        all_cells.extend(_fe_cells(fe_runs))
        skills_included.append("feature_engineering")

    ms_runs = [r for r in session_store.get("model_selector", []) if r.get("status") == "complete"]
    if ms_runs:
        all_cells.extend(_model_cells(ms_runs))
        skills_included.append("model_selector")

    all_cells.extend(_next_steps_cell(session, session_store))

    notebook = {
        "nbformat": 4,
        "nbformat_minor": 5,
        "metadata": {
            "kernelspec": {
                "display_name": "Python 3 (ipykernel)",
                "language": "python",
                "name": "python3",
            },
            "language_info": {"name": "python", "version": "3.11.0"},
        },
        "cells": all_cells,
    }

    n_cells   = len(all_cells)
    skill_str = ", ".join(skills_included) if skills_included else "session overview only"
    summary   = (
        f"{n_cells} cells covering: {skill_str}"
        + (f" | problem: {problem[:60]}{'...' if len(problem) > 60 else ''}" if problem else "")
    )

    return {
        "notebook_json":   json.dumps(notebook, indent=2),
        "filename":        filename,
        "cells_generated": n_cells,
        "skills_included": skills_included,
        "summary":         summary,
    }
